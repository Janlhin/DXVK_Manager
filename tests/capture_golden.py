"""Capture the exact output of the config layer, so a refactor can be checked.

Run this BEFORE restructuring and again after: the files must be byte
identical, which proves the move changed no behaviour.
"""

from __future__ import annotations

import json
import os
import re
import sys
import tempfile
from pathlib import Path

# A throwaway profile keeps settings at their defaults, so the capture does not
# depend on whatever the developer has configured.
os.environ.setdefault("DXVK_MANAGER_HOME", str(Path(tempfile.gettempdir()) / "dxvk-golden"))
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from dxvk_toolkit import confbuild, confspec  # noqa: E402

GOLDEN = Path(__file__).resolve().parent / "golden"

# The header carries the generation time, which changes on every run.
_STAMP = re.compile(r"# Generated by DXVK Version Manager \([^)]*\)")


def normalize(text: str) -> str:
    """Blank out the parts that legitimately differ between runs."""
    return _STAMP.sub("# Generated by DXVK Version Manager (TIMESTAMP)", text)

# Option sets chosen to cover: nothing selected, one simple option, several
# sections at once, booleans, numbers with a bare form, and a multi-section key.
CASES: dict[str, dict[str, object]] = {
    "empty": {},
    "single": {"maxFrameRate": 60},
    "booleans": {"enableHDR": True, "tearFree": False, "hud": "fps"},
    "multi_section": {"maxFrameRate": 120, "maxFrameLatency": 1, "syncInterval": 0},
    "strings": {"deviceFilter": "NVIDIA GeForce RTX", "customDeviceDesc": "GPU"},
    "every_simple": {
        "maxFrameRate": 90, "syncInterval": 1, "presentInterval": 0,
        "maxFrameLatency": 2, "tearFree": True, "enableHDR": True,
        "samplerAnisotropy": 16, "samplerLodBias": -0.5, "numCompilerThreads": 4,
        "enableGraphicsPipelineLibrary": True, "enableAsync": True,
        "maxFeatureLevel": "12_1", "deviceFilter": "", "deferSurfaceCreation": True,
        "hud": "fps,frametimes",
    },
}


def main() -> int:
    GOLDEN.mkdir(parents=True, exist_ok=True)
    model = confspec.load_model()

    # 1) The option catalogue itself: keys, labels, docs, tiers.
    catalogue = [
        {
            "key": group.key,
            "label": group.label,
            "type": group.type,
            "tier": confspec.tier_of(group.key, group.members[0].section if group.members else ""),
            "sections": [member.section for member in group.members],
            "qualified": [member.qualified for member in group.members],
            "summary": group.summary(120),
            "example": group.example,
        }
        for group in model.groups
    ]
    (GOLDEN / "catalogue.json").write_text(
        json.dumps(catalogue, ensure_ascii=False, indent=1), encoding="utf-8"
    )

    # 2) One generated file per case, in both flavours:
    #    conf_*  keeps the documentation comments (the default)
    #    plain_* omits them (same bytes as before the comment feature existed)
    for name, values in CASES.items():
        text = confbuild.build_conf(model.groups, values, section_order=model.section_order)
        (GOLDEN / f"conf_{name}.txt").write_text(normalize(text), encoding="utf-8", newline="")
        plain = confbuild.build_conf(model.groups, values,
                                     section_order=model.section_order, comments=False)
        (GOLDEN / f"plain_{name}.txt").write_text(normalize(plain), encoding="utf-8", newline="")

    print(f"catalogue: {len(catalogue)} options")
    print(f"conf cases: {len(CASES)} (with and without comments)")
    print("written to", GOLDEN)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
