"""The standalone configurator's bridge: what QML can call.

The full application's bridge exposes 56 slots about scanning games,
downloading versions and installing DLLs. None of that exists in a tool whose
job is "given a dxvk.conf, produce a customised one", so this bridge is small
and explicit about what it does.

The one conceptual difference from the full app: there, a "target" is a game
folder the file gets written into; here, the target is the .conf file itself.
The user opens a file, edits it and saves it back.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from PySide6.QtCore import QCoreApplication, QObject, Signal, Slot

from .. import confkit
from ..confkit import build_conf, build_model, parse_config_values
from ..confkit.validate import MAX_CONF_BYTES, ValidationError
from ..ui import config_store
from ..ui.conf_model import ConfigListModel
from .assets import asset_path
from .store import settings

TRANSLATION_CONTEXT = "Standalone"

# The comment at the top of a generated file names the tool that wrote it.
# The full application says "DXVK Version Manager"; this one is a separate
# program, so it must not claim the other tool's name.
FILE_HEADER = "# Generated by DXVK Configurator ({date})\n"


def _tr(text: str) -> str:
    """Translate a UI string under the standalone's own context."""
    return QCoreApplication.translate(TRANSLATION_CONTEXT, text)


def configure_catalogue() -> None:
    """Point the pure configuration core at this tool's language and assets.

    The full application does this in :mod:`dxvk_toolkit.confspec`; the
    standalone does not import that module (it would drag in the Steam
    scanner and the version cache), so it configures the core itself.
    """
    confkit.configure(
        lang=str(settings.get("docs_language") or "zh"),
        assets_dir=asset_path("dxvk.conf.zh.json").parent,
    )


class ConfiguratorBridge(QObject):
    """Everything the standalone configurator's QML can do."""

    statusMessage = Signal(str, str)      # text, kind (info/ok/warn/error)
    fileOpened = Signal(str, str)         # path, display name
    presetsChanged = Signal()
    languageChanged = Signal(str)         # the new language code

    def __init__(self, parent: Any = None) -> None:
        super().__init__(parent)
        configure_catalogue()
        self.config = ConfigListModel(self)
        self._model: Any = None
        self._path: Path | None = None
        self._values: dict[str, Any] = {}
        self._reference: Path | None = None

    # -- reference catalogue ----------------------------------------------
    @Slot(result=str)
    def loadConfig(self) -> str:
        """Load the option catalogue from the reference dxvk.conf."""
        source = self._reference_source()
        self._model = self._build_model(source)
        self.config.set_groups(self._model.groups)
        stored = str(settings.get("config_mode") or "simple")
        self.config.apply_filter("", stored if stored in ("simple", "advanced", "full") else "simple")
        count = len(self._model.groups)
        if count:
            self.statusMessage.emit(
                _tr("共 {} 个选项（{}）").format(count, source.name if source else ""),
                "ok",
            )
        else:
            self.statusMessage.emit(_tr("未找到参考文件"), "warn")
        return str(self._model.source_path or "")

    def _build_model(self, source: Path | None) -> Any:
        """Parse the reference file into the option model."""
        if source is None:
            return build_model("", source="no reference file")
        try:
            if source.stat().st_size > MAX_CONF_BYTES:
                raise ValidationError(
                    f"reference file too large: {source.stat().st_size} bytes "
                    f"exceeds limit of {MAX_CONF_BYTES}"
                )
            text = source.read_text(encoding="utf-8", errors="replace")
        except OSError as exc:
            return build_model("", source=f"unreadable reference: {exc}")
        return build_model(text, source=str(source), path=source)

    def _rebuild_model(self) -> None:
        """Rebuild the option list, keeping the current selection.

        The option names, their explanations and the generated comments come
        from the pure core, which caches its catalogue per language. After a
        language switch that cache has to be rebuilt - otherwise the list
        would keep showing the previous language's wording.
        """
        if self._model is None:
            return
        source = self._reference_source()
        self._model = self._build_model(source)
        self.config.set_groups(self._model.groups)
        if self._values:
            self.config.apply_values(dict(self._values))
        search, mode, section = self.config.current_filter()
        self.config.apply_filter(search, mode, section)

    def _reference_source(self) -> Path | None:
        """The dxvk.conf the option list is built from."""
        configured = str(settings.get("reference_conf") or "").strip()
        if configured:
            candidate = Path(configured)
            if candidate.is_file():
                return candidate
        bundled = asset_path("dxvk.conf")
        if bundled.is_file():
            return bundled
        return None

    # -- the open file ----------------------------------------------------
    @Slot(str, result=str)
    def openFile(self, path: str) -> str:
        """Open a .conf file and show its options as selected."""
        target = Path(path)
        try:
            text = target.read_text(encoding="utf-8", errors="replace")
        except OSError as exc:
            self.statusMessage.emit(_tr("读取失败：{}").format(exc), "error")
            return ""
        values, unknown = parse_config_values(text, self._model)
        self._path = target
        self._values = values
        self.config.apply_values(values)
        settings.set("last_file", str(target))
        settings.set("last_dir", str(target.parent))
        self.fileOpened.emit(str(target), target.name)
        summary = _tr("已从 {} 导入 {} 个选项").format(target.name, len(values))
        if unknown:
            summary += _tr("，另有 {} 个选项不在参考文件里（已忽略）").format(len(unknown))
        self.statusMessage.emit(summary, "ok")
        return summary

    @Slot(result=str)
    def currentFile(self) -> str:
        """Path of the open file ("" when none is open)."""
        return str(self._path or "")

    @Slot(result=bool)
    def hasFile(self) -> bool:
        return self._path is not None

    @Slot(result=str)
    def saveFile(self) -> str:
        """Write the generated text back to the open file."""
        if self._path is None:
            self.statusMessage.emit(_tr("没有打开的文件"), "warn")
            return ""
        try:
            self._path.write_text(self.previewConfig(), encoding="utf-8", newline="\r\n")
        except OSError as exc:
            self.statusMessage.emit(_tr("写入失败：{}").format(exc), "error")
            return ""
        self.statusMessage.emit(_tr("已写入 {}").format(self._path), "ok")
        return str(self._path)

    @Slot(result=str)
    def exportConfig(self) -> str:
        """Save the generated text to a new file."""
        from PySide6.QtWidgets import QFileDialog

        start = str(settings.get("last_dir") or "")
        target, _filter = QFileDialog.getSaveFileName(
            None, _tr("导出 dxvk.conf"), str(Path(start) / "dxvk.conf") if start else "dxvk.conf",
            "DXVK 配置 (*.conf);;所有文件 (*)"
        )
        if not target:
            return ""
        try:
            Path(target).write_text(self.previewConfig(), encoding="utf-8", newline="\r\n")
        except OSError as exc:
            self.statusMessage.emit(_tr("写入失败：{}").format(exc), "error")
            return ""
        settings.set("last_dir", str(Path(target).parent))
        self.statusMessage.emit(_tr("已导出到 {}").format(target), "ok")
        return target

    @Slot(result=str)
    def importConfig(self) -> str:
        """Read a .conf file and show its options as selected."""
        from PySide6.QtWidgets import QFileDialog

        start = str(settings.get("last_dir") or "")
        path, _filter = QFileDialog.getOpenFileName(
            None, _tr("导入 dxvk.conf"), start, "DXVK 配置 (*.conf);;所有文件 (*)"
        )
        if not path:
            return ""
        return self.openFile(path)

    # -- options ----------------------------------------------------------
    @Slot(str, bool, str)
    def setOption(self, key: str, enabled: bool, value: str) -> None:
        self.config.set_option(key, enabled, value)

    @Slot(str)
    def toggleSection(self, label: str) -> None:
        self.config.toggleSection(label)

    @Slot(str, str, str)
    def filterConfig(self, search: str, mode: str, section: str) -> None:
        self.config.apply_filter(search, mode, section)

    @Slot(result=str)
    def previewConfig(self) -> str:
        """The generated dxvk.conf, as it would be written."""
        if self._model is None:
            return "# " + _tr("还没有载入参考文件") + "\n"
        return build_conf(
            self._model.groups,
            self.config.values,
            section_order=self._model.section_order,
            comments=bool(settings.get("conf_comments", True)),
            header=FILE_HEADER,
        )

    @Slot(result=int)
    def selectedOptionCount(self) -> int:
        return len([v for v in self.config.values.values() if v not in (None, "")])

    @Slot(result=str)
    def modifiedSummary(self) -> str:
        return self.config.modifiedSummary()

    @Slot(str)
    def resetOption(self, key: str) -> None:
        self.config.resetOption(key)
        self.statusMessage.emit(_tr("已还原：{}").format(key), "info")

    @Slot()
    def clearConfig(self) -> None:
        """Drop every selection."""
        self.config.apply_values({})

    # -- presets ----------------------------------------------------------
    @Slot(result=list)
    def listPresets(self) -> list:
        return config_store.preset_names(settings)

    @Slot(str, result=int)
    def applyPreset(self, name: str) -> int:
        """Apply a preset to the open file; returns how many options it set."""
        if name == config_store.PURE_PRESET:
            self.clearConfig()
            return 0
        preset = config_store.preset_values(name, settings)
        if not preset or self._model is None:
            return 0
        available = {row["key"] for row in self.config._all}
        applied = 0
        for key, value in preset.items():
            if key not in available:
                continue
            if isinstance(value, bool):
                self.config.set_option(key, value, "")
            else:
                self.config.set_option(key, True, str(value))
            applied += 1
        return applied

    @Slot(str)
    def savePreset(self, name: str) -> None:
        name = name.strip()
        if not name or self._model is None:
            return
        if config_store.is_builtin(name):
            self.statusMessage.emit(_tr("内置预设不能覆盖，请换一个名字"), "warn")
            return
        if config_store.save_preset(name, self.config.values, settings):
            self.statusMessage.emit(_tr("已保存预设「{}」").format(name), "ok")
            self.presetsChanged.emit()

    # -- language ----------------------------------------------------------
    @Slot(str)
    def setLanguage(self, lang: str) -> None:
        """Switch the interface and the option explanations to ``lang``.

        The two travel together on purpose: this tool has one audience, and
        an English interface showing English option explanations is what
        someone who picked English wants. The full application keeps them
        separate because it also serves people who want the original DXVK
        comments in English while reading the interface in Chinese.
        """
        code = "en" if str(lang or "").strip().lower() == "en" else "zh"
        settings.set("ui_lang", code)
        settings.set("docs_language", code)
        from . import app as standalone_app

        standalone_app.set_language(code)
        # The option list is built from the pure core, which caches the
        # catalogue per language - it has to be re-pointed and rebuilt.
        configure_catalogue()
        self._rebuild_model()
        self.languageChanged.emit(code)
        self.statusMessage.emit(
            _tr("已切换到英文") if code == "en" else _tr("已切换到中文"),
            "ok",
        )

    # -- settings ---------------------------------------------------------
    @Slot(str, result="QVariant")
    def getSetting(self, key: str) -> Any:  # noqa: N802 - QML naming
        return settings.get(key)

    @Slot(str, "QVariant")
    def setSetting(self, key: str, value: Any) -> None:  # noqa: N802 - QML naming
        settings.set(key, value)

    @Slot()
    def copyConfig(self) -> None:
        """Put the generated text on the clipboard."""
        from PySide6.QtWidgets import QApplication

        clipboard = QApplication.clipboard()
        if clipboard is not None:
            clipboard.setText(self.previewConfig())
            self.statusMessage.emit(_tr("已复制到剪贴板"), "ok")

    @Slot(result=str)
    def appVersion(self) -> str:
        from .. import APP_VERSION

        return APP_VERSION
