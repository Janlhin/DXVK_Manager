"""Compose a dxvk.conf from the current selection."""

from __future__ import annotations

import re
import time
from collections.abc import Iterable, Mapping, Sequence
from typing import Any

from .base import NUMBER_RE
from .i18n import documentation_overrides
from .model import OptionGroup

HEADER = "# Generated by DXVK Version Manager ({date})\n"


# Characters that force quoting even when the reference writes values bare:
# DXVK reads a value up to the first unquoted whitespace, and '#' or '"'
# would break the line.
_BARE_SAFE_RE = re.compile(r"^[^\s#\"']+$")


def format_value(value: Any, kind: str, *, bare: bool = False) -> str | None:
    """Render one option value the way dxvk.conf expects it.

    Returns None when the value means "leave this option out". DXVK strips
    surrounding quotes while parsing, so quoting is always safe; 'bare' keeps
    enum-style values (Auto, 12_1, 10DE) in the same shape the reference file
    uses for them.
    """
    if value is None:
        return None
    if isinstance(value, bool):
        return "True" if value else None
    text = str(value).strip()
    if text == "":
        return None
    if kind == "boolean":
        lowered = text.lower()
        if lowered in ("true", "1", "yes", "on"):
            return "True"
        return None
    if NUMBER_RE.match(text):
        return text
    if bare and _BARE_SAFE_RE.match(text):
        return text
    escaped = text.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


COMMENT_WIDTH = 76


# Latin words stay whole; CJK has no spaces, so those characters are their own
# tokens and a line can break between any two of them. The whitespace between
# two tokens is kept as its own token, so the words of an English sentence do
# not end up glued together ("SetsenabledHUDelements").
_TOKEN_RE = re.compile(r"[A-Za-z0-9_./\\:+=@-]+|\s+|[^\sA-Za-z0-9_./\\:+=@-]")

# Punctuation that must not start a line (the CJK "kinsoku" rule), so a comment
# never begins with a stray full stop or bracket.
_NO_LINE_START = set("。，、；：！？）】》」』…—·%,.;:!?)]}")


def display_width(text: str) -> int:
    """Width in a monospace editor, where CJK characters take two columns."""
    width = 0
    for char in text:
        code = ord(char)
        wide = (
            0x1100 <= code <= 0x115F
            or 0x2E80 <= code <= 0xA4CF
            or 0xAC00 <= code <= 0xD7A3
            or 0xF900 <= code <= 0xFAFF
            or 0xFE30 <= code <= 0xFE6F
            or 0xFF00 <= code <= 0xFF60
            or 0xFFE0 <= code <= 0xFFE6
            or 0x20000 <= code <= 0x3FFFD
        )
        width += 2 if wide else 1
    return width


def wrap_comment(text: str, width: int = COMMENT_WIDTH) -> list[str]:
    """Format one documentation paragraph as '# ' lines.

    The reference dxvk.conf documents every option above it, and so does the
    generated file. Wrapping measures monospace columns rather than characters
    (Chinese is double width) and breaks between characters for CJK, which has
    no spaces to break on.
    """
    limit = max(8, width - display_width("# "))
    lines: list[str] = []
    current = ""
    tokens = _TOKEN_RE.findall(" ".join(str(text).split()))
    for index, token in enumerate(tokens):
        if not token.strip():
            # Whitespace separates the words of a Latin sentence. It is kept
            # only between two Latin words - the CJK text has no spaces of its
            # own, and the space between a Chinese and a Latin word is not
            # part of the source sentence.
            if not _between_latin_words(tokens, index):
                continue
            if current and not current.endswith(" "):
                current += " "
            continue
        overflows = (current.strip()
                     and display_width(current) + display_width(token) > limit)
        if overflows and token not in _NO_LINE_START:
            lines.append("# " + current.rstrip())
            current = ""
        current += token
    if current.strip():
        lines.append("# " + current.rstrip())
    return lines or ["#"]


def _between_latin_words(tokens: list[str], index: int) -> bool:
    """Is the whitespace at ``index`` between two Latin words?"""
    before = ""
    for token in reversed(tokens[:index]):
        if token.strip():
            before = token
            break
    after = ""
    for token in tokens[index + 1:]:
        if token.strip():
            after = token
            break
    if not before or not after:
        return False
    return _is_latin_word(before[-1]) and _is_latin_word(after[0])


def _is_latin_word(char: str) -> bool:
    """Is this character part of a Latin word (as opposed to CJK)?"""
    return char.isascii() and (char.isalnum() or char in "_./\\:+=@-")


def comment_block(group: OptionGroup, *, lang: str | None = None) -> list[str]:
    """The documentation lines that belong above one option.

    Chinese documentation wins when available (it is what the interface shows),
    otherwise the English text from the reference file is used.
    """
    text = documentation_overrides(lang).get(group.key) or group.comment or group.key
    return wrap_comment(text)


def build_conf(
    groups: Sequence[OptionGroup],
    values: Mapping[str, Any],
    *,
    section_order: Iterable[str] = (),
    include_header: bool = True,
    comments: bool = True,
    header: str = HEADER,
) -> str:
    """Compose a dxvk.conf containing every line the selection implies.

    A single control can cover the same option in several sections; all of
    them are written so the file works regardless of which one the game reads.

    ``header`` names the tool in the comment at the top of the file. It is a
    parameter because two tools generate this file: the full application and
    the standalone configurator.
    """
    buckets: dict[str, list[str]] = {}
    for group in groups:
        rendered = format_value(values.get(group.key), group.type, bare=group.prefers_bare)
        if rendered is None:
            continue
        # The comment is computed once per option, then repeated for every
        # section it appears in: a section can be copied out on its own.
        block = comment_block(group) if comments else []
        for member in group.members:
            lines = buckets.setdefault(member.section, [])
            lines.extend(block)
            lines.append(f"{member.qualified} = {rendered}")

    order: list[str] = []
    for section in list(section_order) + list(buckets.keys()):
        if section in buckets and section not in order:
            order.append(section)

    parts: list[str] = []
    if include_header:
        parts.append(header.format(date=time.strftime("%Y-%m-%d %H:%M")))
    for section in order:
        parts.append(f"# [{section}]")
        parts.extend(buckets[section])
        parts.append("")
    text = "\n".join(parts).rstrip() + "\n"
    if not order and include_header:
        text = header.format(date=time.strftime("%Y-%m-%d %H:%M"))
        text += "# No options selected yet.\n"
    return text


def count_lines(text: str) -> int:
    return sum(1 for line in text.splitlines() if line.strip() and not line.lstrip().startswith("#"))


def selection_summary(values: Mapping[str, Any]) -> str:
    active = [key for key, value in values.items() if _active(value)]
    if not active:
        return "no options selected"
    return f"{len(active)} option(s) selected"


def _active(value: Any) -> bool:
    if isinstance(value, bool):
        return value
    if value is None:
        return False
    return str(value).strip() != ""
